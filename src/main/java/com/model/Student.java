package com.model;
public class Student 
{
	int sid;
	String sname;
	double smarks;
	public int getSid() 
	{
		return sid;
	}
	public void setSid(int sid) 
	{
		this.sid = sid;
	}
	public String getSname() 
	{
		return sname;
	}
	public void setSname(String sname) 
	{
		this.sname = sname;
	}
	public double getSmarks() 
	{
		return smarks;
	}
	public void setSmarks(double smarks) 
	{
		this.smarks = smarks;
	}
	

}
